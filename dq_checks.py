"""
HR data quality checks for personnel records.

Data: Human Resources Data Set by Dr. Rich Huebner (fictional, 311 employees).
It has real-looking quality problems: trailing spaces, lost leading zeros, two-digit
years, missing manager IDs and one manager name with two IDs.

The rules run in SQL (DuckDB, see ./sql/rules.sql) so they can move to any warehouse
such as Snowflake with small changes. Python only loads the data, applies the
automatic fixes and writes the reports.

Steps
1. Load the raw file and run every rule. Each failing record gets one row in the issue log.
2. Apply the fixes that are safe to automate (trim text, pad zip codes, fix the century
   of birth dates, fill manager IDs from the manager name).
3. Run the rules again. Everything left needs a person to look at it.

Output: ./output/issue_log_before.csv, ./output/issue_log_after.csv, ./results.md

Run:  python dq_checks.py
"""
from pathlib import Path

import duckdb
import pandas as pd

SOURCE = "https://raw.githubusercontent.com/bisquittz/Human-Resources-Dataset-Analysis/main/HRDataset_v14.csv"
HERE = Path(__file__).parent
OUT = HERE / "output"
OUT.mkdir(exist_ok=True)
RULES_SQL = (HERE / "sql" / "rules.sql").read_text()


def run_rules(df: pd.DataFrame) -> pd.DataFrame:
    con = duckdb.connect()
    con.register("employees", df)
    issues = con.execute(RULES_SQL).df()
    con.close()
    return issues


def summary(issues: pd.DataFrame, n: int) -> pd.DataFrame:
    s = (issues.groupby(["rule_id", "rule", "severity"]).EmpID.nunique()
         .rename("records").reset_index().sort_values(["severity", "records"], ascending=[True, False]))
    s["share_%"] = (s["records"] / n * 100).round(1)
    return s


def fix(df: pd.DataFrame) -> pd.DataFrame:
    f = df.copy()
    for c in f.select_dtypes(include=["object", "string"]).columns:
        f[c] = f[c].astype("string").str.strip()
    f["Zip"] = f["Zip"].astype(int).astype(str).str.zfill(5)
    dob = pd.to_datetime(f["DOB"], format="%m/%d/%y")
    dob = dob.where(dob.dt.year <= 2005, dob - pd.DateOffset(years=100))
    f["DOB"] = dob.dt.strftime("%m/%d/%Y")
    # Fill a missing ManagerID only when the manager name maps to exactly one ID.
    ids = f.dropna(subset=["ManagerID"]).groupby("ManagerName")["ManagerID"].agg(lambda s: s.unique().tolist())
    one = {k: v[0] for k, v in ids.items() if len(v) == 1}
    f["ManagerID"] = f["ManagerID"].fillna(f["ManagerName"].map(one))
    return f


raw = pd.read_csv(SOURCE, encoding="utf-8-sig", dtype={"Zip": int})
raw["DOB_raw_format"] = raw["DOB"]
n = len(raw)

before = run_rules(raw)
fixed = fix(raw)
after = run_rules(fixed)
before.to_csv(OUT / "issue_log_before.csv", index=False)
after.to_csv(OUT / "issue_log_after.csv", index=False)

rec_before = before.EmpID.nunique()
rec_after = after.EmpID.nunique()
crit_before = before[before.severity == "1 critical"].EmpID.nunique()
crit_after = after[after.severity == "1 critical"].EmpID.nunique()

with open(HERE / "results.md", "w") as f:
    f.write("# Results (generated by dq_checks.py)\n\n")
    f.write(f"- Records checked: {n}\n")
    f.write(f"- Records with at least one issue: {rec_before} ({rec_before/n*100:.1f}%) before, "
            f"{rec_after} ({rec_after/n*100:.1f}%) after automatic fixes\n")
    f.write(f"- Records with a critical issue: {crit_before} ({crit_before/n*100:.1f}%) before, "
            f"{crit_after} ({crit_after/n*100:.1f}%) after\n\n")
    f.write("## Before fixes\n\n" + summary(before, n).to_markdown(index=False) + "\n\n")
    f.write("## After fixes (needs a person to review)\n\n" + summary(after, n).to_markdown(index=False) + "\n")

print(open(HERE / "results.md").read())
